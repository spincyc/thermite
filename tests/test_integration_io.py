class Embedding(unittest.TestCase):
    def test_each_device_script_carries_the_io_then_the_shared_device_parts_once(self):
        for module in (avpro_telnet, pyatv_http, sony_adcp, sony_ip_control):
            with self.subTest(integration=module.NAME):
                house = inventory(module)
                text = module.files(house["devices"], House(house))[module.rule_path(house["devices"][0])]
                self.assertNotIn(_io.MARK, text)
                self.assertNotIn(_io.DEVICE_MARK, text)
                self.assertEqual(text.count("const thermiteIO = "), 1)
                self.assertEqual(text.count("const thermiteDevice = "), 1)
                self.assertLess(text.index("const thermiteIO = "), text.index("const thermiteDevice = "))
                # The shared parts carry the command record's table, with this integration's tally.
                self.assertNotIn(unfilled(_commands.TABLE), text)
                self.assertEqual(text.count(f'"tally":"{module.NAME}_commands"'), 1)

    def test_the_shared_device_parts_are_optional_but_once_and_after_the_io(self):
        self.assertEqual(_io.embed(f"a\n{_io.MARK}\nb\n"), f"a\n{_io.SOURCE.read_text()}\nb\n")
        for bad in (f"{_io.MARK}\n{_io.DEVICE_MARK}\n{_io.DEVICE_MARK}\n", f"{_io.DEVICE_MARK}\n{_io.MARK}\n",
                    f"{_io.MARK}\nx = 1; {_io.DEVICE_MARK}\n", f"{_io.DEVICE_MARK}\n"):
            with self.subTest(source=bad), self.assertRaises(ValueError):
                _io.embed(bad, "example")

    def test_the_shared_device_parts_need_the_name_of_the_integration_whose_script_takes_them(self):
        marked = f"{_io.MARK}\n{_io.DEVICE_MARK}\n"
        with self.assertRaisesRegex(ValueError, "must name its integration"):
            _io.embed(marked)
        self.assertEqual(_io.embed(marked, "example"), f"{_io.SOURCE.read_text()}\n{_io.device('example')}\n")

    def test_a_script_that_opens_no_connection_takes_the_shared_device_parts_alone(self):
        self.assertEqual(_io.shared(f"a\n{_io.DEVICE_MARK}\nb\n", "example"), f"a\n{_io.device('example')}\nb\n")
        for bad in ("a\n", f"{_io.DEVICE_MARK}\n{_io.DEVICE_MARK}\n", f"x = 1; {_io.DEVICE_MARK}\n", f"{_io.MARK}\n{_io.DEVICE_MARK}\n"):
            with self.subTest(source=bad), self.assertRaises(ValueError):
                _io.shared(bad, "example")


class Filling(unittest.TestCase):
    SOURCE = "// a rule\nconst DEVICES = null;\n  const KEYS = null;\nconst SEND = true;\nrun();\n"
    ORIGIN = AREA / "lib/oh_integrations/example.js"

    def test_each_constant_takes_its_value_under_the_header_that_names_the_source(self):
        text = fill(self.SOURCE, {"DEVICES": [{"id": "den_device"}], "KEYS": {"up": 1}}, self.ORIGIN, keep=(RULE_SENDS,))
        self.assertEqual(text, "// Generated by bin/thermite generate from lib/oh_integrations/example.js and\n"
                               "// instance/devices.yaml; do not edit.\n"
                               '// a rule\nconst DEVICES = [{"id":"den_device"}];\n  const KEYS = {"up":1};\n'
                               "const SEND = true;\nrun();\n")
        # The header is what tells thermite generate --prune that a file is its own.
        self.assertIn(generate.MARK, text.encode()[:512])
        routed = fill(self.SOURCE, {"DEVICES": [], "KEYS": {}}, self.ORIGIN, part="the routing in")
        self.assertTrue(routed.startswith("// Generated by bin/thermite generate from lib/oh_integrations/example.js "
                                          "and the routing in\n// instance/devices.yaml; do not edit.\n"))

    def test_a_table_can_keep_a_line_to_each_entry_and_a_second_fill_adds_no_header(self):
        first = fill(self.SOURCE, {"DEVICES": [1, 2]}, self.ORIGIN, encode=indented)
        self.assertIn("const DEVICES = [\n 1,\n 2\n];\n", first)
        second = fill(first, {"KEYS": {}}, "automation/js/example.js", header=False)
        self.assertEqual(second, first.replace(unfilled("KEYS"), "const KEYS = {};"))

    def test_a_source_without_its_constant_or_with_it_twice_is_refused_by_name(self):
        once = unfilled("DEVICES")
        for source in (self.SOURCE.replace(once, "const DEVICES = [];"), self.SOURCE + once + "\n",
                       self.SOURCE.replace(once, f"{once} // {once}"), self.SOURCE + f"// was {once}\n"):
            with self.subTest(source=source), self.assertRaisesRegex(
                    ValueError, r"example\.js must contain the line 'const DEVICES = null;' exactly once"):
                fill(source, {"DEVICES": []}, self.ORIGIN)
        with self.assertRaisesRegex(ValueError, "must contain the line 'const SEND = true;' exactly once"):
            fill(self.SOURCE.replace(RULE_SENDS, "  " + RULE_SENDS), {"DEVICES": []}, self.ORIGIN, keep=(RULE_SENDS,))

    def test_no_rendered_script_of_the_example_keeps_an_unfilled_constant(self):
        unfilled_line = re.compile(r"^\s*const ([A-Z_]+) = null;$", re.MULTILINE)
        for path, text in oh_render.build(House(json.loads((AREA / "instance/devices.yaml").read_text()))).render().items():
            if path.endswith(".js") and isinstance(text, str):
                # A device the routing gives no actor keeps this one: its rule runs without.
                self.assertLessEqual(set(unfilled_line.findall(text)), {lifecycle_io.CUSTOM}, path)

    def test_every_rule_an_integration_renders_carries_the_generated_header(self):
        # Without it thermite generate --prune takes a stale rule for the owner's file.
        import oh_integrations
        from tests import test_generated_output
        rules = {module.RULE.removesuffix(".js") for module in oh_integrations.REGISTRY if module.RULE}
        seen = set()
        for name, house in test_generated_output.houses().items():
            data = json.loads(house.read_text(encoding="utf-8")) if isinstance(house, Path) else copy.deepcopy(house)
            for path, text in oh_render.build(House(data)).render().items():
                rule = next((rule for rule in rules if path.startswith(rule) and path.endswith(".js")), None)
                if rule:
                    seen.add(rule)
                    self.assertIn(generate.MARK, text.encode()[:512], f"{name}: {path}")
        # An IR rule needs a commissioned profile, which none of these houses has.
        self.assertEqual(rules - seen, {"automation/js/globalcache_ir"})

    def test_only_fill_writes_a_script_constant(self):
        by_hand = re.compile(r"""["']const [A-Z_]+ = null;["']|const [A-Z_]+ = (["']\s*\+|\{)""")
        found = {path.relative_to(AREA).as_posix() for path in (AREA / "lib").rglob("*.py")
                 if "tests" not in path.parts and by_hand.search(path.read_text(encoding="utf-8"))}
        # The routing lifecycle writes a whole generated actor, CONFIG with it.
        self.assertEqual(found, {"lib/oh_features/routing/lifecycle_io.py"})


class ScriptBase(unittest.TestCase):
    def test_one_script_per_device_named_after_the_rule_and_the_device(self):
        rule_path, files = _script.per_device("automation/js/example.js", lambda devices: devices[0]["id"])
        devices = [{"id": "den_device"}, {"id": "attic_device"}]
        self.assertEqual(rule_path(devices[0]), _io.script_path("automation/js/example.js", devices[0]))
        self.assertEqual(files(devices, None), {rule_path(device): device["id"] for device in devices})

    def test_aiming_changes_the_one_device_and_names_a_script_or_device_that_is_absent(self):
        files = {"a.js": 'x\nconst DEVICES = [{"id":"den_device","host":"192.0.2.10"},{"id":"attic_device","host":"192.0.2.11"}];\ny\n',
                 "b.js": "const DEVICES = [];\n"}
        aimed = _script.aimed(files, ("missing.js", "a.js"), {"id": "den_device"}, lambda entry: entry.update(host="127.0.0.1"))
        self.assertEqual(aimed, {**files, "a.js": 'x\nconst DEVICES = [{"id":"den_device","host":"127.0.0.1"},'
                                                  '{"id":"attic_device","host":"192.0.2.11"}];\ny\n'})
        with self.assertRaisesRegex(ValueError, "missing.js has no device den_device"):
            _script.aimed(files, ("missing.js",), {"id": "den_device"}, lambda entry: None)
        with self.assertRaisesRegex(ValueError, "b.js has no device den_device"):
            _script.aimed(files, ("b.js",), {"id": "den_device"}, lambda entry: None)


class DeviceContexts(unittest.TestCase):
    def test_control_fixture_excludes_observer_device_scripts(self):
        check = controls.Check(House(projectors()), log=lambda _: None)
        self.addCleanup(lambda: [stand_in.server.stop() for stand_in in check.stand_ins.values()])
        files = check.conf()
        self.assertIn(sony_adcp.rule_path({"id": "den_device"}), files)
        self.assertNotIn(sony_adcp.rule_path({"id": "attic_device"}), files)

    def test_one_context_per_device_with_independent_poll_ids_and_retargeting(self):
        for module in (avpro_telnet, pyatv_http, sony_adcp, sony_ip_control):
            with self.subTest(integration=module.NAME):
                house = inventory(module)
                original = house["devices"][0]
                second = {**original, "id": "other_device", "ip": "192.0.2.240"}
                devices = [original, second]
                files = module.files(devices, House(house))
                self.assertEqual(set(files), {module.rule_path(d) for d in devices})
                for device in devices:
                    text = files[module.rule_path(device)]
                    line = next(line for line in text.splitlines() if line.startswith("const DEVICES = "))
                    self.assertEqual([d["id"] for d in json.loads(line[len("const DEVICES = "):-1])], [device["id"]])
                    self.assertIn("${DEVICES[0].id}_poll", text)
                aimed = module.aim(files, original, "127.0.0.1:40123")
                self.assertEqual(aimed[module.rule_path(second)], files[module.rule_path(second)])
                self.assertNotEqual(aimed[module.rule_path(original)], files[module.rule_path(original)])


@unittest.skipUnless(all(os.environ.get(name) for name in ("THERMITE_JAVA", "THERMITE_ECJ", "THERMITE_RUNTIME", "THERMITE_GRAAL")),
                     "native fault test needs cached pinned Java/runtime/ECJ/Graal paths")
class NativeIo(unittest.TestCase):
    def test_real_jvm_deadlines_frame_bounds_cookies_and_worker_ownership(self):
        jars = sorted(Path(os.environ["THERMITE_RUNTIME"]).rglob("*.jar"))
        jars += sorted(Path(os.environ["THERMITE_GRAAL"]).rglob("*.jar"))
        classpath = os.pathsep.join(str(p) for p in jars)
        java = os.environ["THERMITE_JAVA"]
        with tempfile.TemporaryDirectory() as tmp:
            result = subprocess.run([java, "-jar", os.environ["THERMITE_ECJ"], "-21", "-proc:none", "-cp", classpath,
                                     "-d", tmp, str(AREA / "tests/integration_io/NativeTest.java")],
                                    capture_output=True, text=True, timeout=30)
            self.assertEqual(result.returncode, 0, result.stdout + result.stderr)
            result = subprocess.run([java, "-cp", tmp + os.pathsep + classpath, "NativeTest", str(AREA / "lib/oh_integrations/_io.js")],
                                    capture_output=True, text=True, timeout=30)
            self.assertEqual(result.returncode, 0, result.stdout + result.stderr)
            self.assertIn("deadlines, cookie ownership and disposal passed", result.stdout)
