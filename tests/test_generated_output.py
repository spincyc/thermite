HEADER = """\
# SHA-256 of every file `thermite generate` writes for the fictional houses of
# tests/test_generated_output.py, which compares them. An entry is
# <house>/<path>, or */<path> for a file that every house generates with the
# same bytes. One entry for each generated file, sorted, with an empty line
# between entries: Git merges two branches' changes to neighbouring lines only
# when a line between them is unchanged. Never edit this file or resolve a
# conflict in it by hand; rewrite it:
#
#     python -m tests.test_generated_output --write
"""
