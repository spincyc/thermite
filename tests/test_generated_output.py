def houses() -> dict[str, dict | Path]:
    """Name -> house: the example's file, and the others as data."""
    found: dict[str, dict | Path] = {"example": EXAMPLE}
    for name, phase in sorted(test_read_only.HOUSES):
        found[f"{name}.{phase}"] = test_read_only.house(name, phase)
    found["routed"] = ROUTED
    return found


def written(house: Path, root: Path) -> dict[str, bytes]:
    """Path below `root` -> bytes of every file `thermite generate --house
    HOUSE` writes there."""
    out, problems = io.StringIO(), io.StringIO()
    # The verb reads versions.json and instance/host.yaml from the selected
    # site; these are this checkout's, whatever THERMITE_SITE selects.
    with mock.patch.object(generate, "AREA", AREA), contextlib.redirect_stdout(out), \
            contextlib.redirect_stderr(problems):
        try:
            status = generate.main(["--house", str(house), "--conf", str(root / "conf"), "--root", str(root)])
        except SystemExit as stopped:
            status = stopped.code
    if status:
        raise AssertionError(f"thermite generate --house {house} exited {status}:\n{problems.getvalue()}{out.getvalue()}")
    return {path.relative_to(root).as_posix(): path.read_bytes() for path in root.rglob("*") if path.is_file()}


def generated(out: Path) -> dict[str, dict[str, bytes]]:
    """House name -> its files, each house generated into `out`/<name>/."""
    trees = {}
    with tempfile.TemporaryDirectory() as scratch:
        for name, house in houses().items():
            if not isinstance(house, Path):
                data, house = house, Path(scratch) / f"{name}.json"
                house.write_text(json.dumps(data), encoding="utf-8")
            (out / name).mkdir()
            trees[name] = written(house, out / name)
    return trees


def digests(trees: dict[str, dict[str, bytes]]) -> dict[str, str]:
    """Entry -> SHA-256; a file every house generates alike is one entry,
    under EVERY."""
    same = {path for path in set.intersection(*(set(tree) for tree in trees.values()))
            if len({tree[path] for tree in trees.values()}) == 1}
    found = {f"{EVERY}/{path}": content for path, content in next(iter(trees.values())).items() if path in same}
    found.update({f"{name}/{path}": content for name, tree in trees.items() for path, content in tree.items()
                  if path not in same})
    return {entry: hashlib.sha256(content).hexdigest() for entry, content in found.items()}


def current() -> dict[str, str]:
    with tempfile.TemporaryDirectory() as scratch:
        return digests(generated(Path(scratch)))


def text(entries: dict[str, str]) -> str:
    """The record of `entries`, as --write writes it."""
    return HEADER + "".join(f"\n{digest}  {entry}\n" for entry, digest in sorted(entries.items()))


def recorded(record: str) -> dict[str, str]:
    """Entry -> SHA-256 of a record's text; a line that is no entry (what a
    merge conflict leaves, say) is none, and text() then differs from it."""
    lines = [line.split("  ", 1) for line in record.splitlines() if line and not line.startswith("#")]
    return {line[1]: line[0] for line in lines if len(line) == 2}


def differences(old: dict[str, str], new: dict[str, str]) -> list[str]:
    """One line for each entry that `new` adds to `old`, removes or changes."""
    lines = []
    for entry in sorted(set(old) | set(new)):
        if entry not in old:
            lines.append(f"added    {entry}")
        elif entry not in new:
            lines.append(f"removed  {entry}")
        elif old[entry] != new[entry]:
            lines.append(f"changed  {entry}")
    return lines


def listed(lines: list[str]) -> str:
    more = [f"... and {len(lines) - SHOWN} more"] if len(lines) > SHOWN else []
    return "\n".join(f"  {line}" for line in lines[:SHOWN] + more)


class GeneratedOutput(unittest.TestCase):
    def test_every_generated_file_has_its_recorded_bytes(self):
        now = current()
        record = RECORD.read_text(encoding="utf-8")
        changes = differences(recorded(record), now)
        if changes:
            self.fail(f"thermite generate no longer writes what {RECORD.relative_to(AREA)} records, in "
                      f"{len(changes)} of {len(now)} files:\n{listed(changes)}\n"
                      f"If these files are meant to change, rewrite the record and commit it with the change:\n"
                      f"  {REWRITE}")
        if record != text(now):
            self.fail(f"{RECORD.relative_to(AREA)} is not as --write writes it (its order, spacing or header, an "
                      f"entry twice, or a line that is no entry); rewrite it:\n  {REWRITE}")


def main(argv: list[str]) -> int:
    parser = argparse.ArgumentParser(prog="python -m tests.test_generated_output",
                                     description="Compare what thermite generate writes for the fictional houses "
                                                 "with tests/generated_output.sha256 (no switch), or:")
    mode = parser.add_mutually_exclusive_group()
    mode.add_argument("--write", action="store_true", help="rewrite tests/generated_output.sha256 and say what changed")
    mode.add_argument("--out", type=Path, metavar="DIR",
                      help="write every house's generated files to DIR/<house>/ (DIR must be empty or absent)")
    arguments, rest = parser.parse_known_args(argv)
    if arguments.out is not None:
        arguments.out.mkdir(parents=True, exist_ok=True)
        if any(arguments.out.iterdir()):
            parser.error(f"{arguments.out} is not empty")
        trees = generated(arguments.out.resolve())
        print(f"wrote {sum(map(len, trees.values()))} files of {len(trees)} houses to {arguments.out}")
        return 0
    if not arguments.write:
        unittest.main(argv=[sys.argv[0], *rest])
    now = current()
    changes = differences(recorded(RECORD.read_text(encoding="utf-8")) if RECORD.exists() else {}, now)
    RECORD.write_text(text(now), encoding="utf-8")
    print(f"wrote {RECORD.relative_to(AREA)}: {len(now)} files, {len(changes)} added, removed or changed"
          + (":\n" + "\n".join(f"  {line}" for line in changes) if changes else ""))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
