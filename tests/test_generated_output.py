"""Every file `thermite generate` writes for a set of fictional houses has
the bytes that tests/generated_output.sha256 records.

Git ignores conf/, metrics/ and deploy/, so nothing else shows that a change
to the generator changed what it writes, or left it alone. The houses are
the example (instance/devices.yaml), one house per integration and phase
(tests/test_read_only.py) and ROUTED below; each goes through the verb
itself, on this checkout's versions.json and instance/host.yaml.

When the generated bytes are meant to change, rewrite the record and commit
it with the change; its diff then names the generated files that changed:

    python -m tests.test_generated_output --write

To see the bytes themselves, write every house's files on both commits and
compare the two trees:

    python -m tests.test_generated_output --out DIR
"""
