"""Persist the finite native-port boundary before starting the native runtime."""
from __future__ import annotations

from pathlib import Path
import json
import re

from oh_install.model import Check, Command, Step, Task

UNIT = "thermite-native-boundary.service"
UNIT_FILE = Path("/etc/systemd/system") / UNIT
RULE_FILE = Path("/etc/thermite-native.nft")
MARKER = "# Thermite native listener boundary; generated by the installer.\n"


def rule_text(host):
    from oh_access.native_boundary import firewall_rules
    return MARKER + f"# Ports: {host['http_port']},{host['https_port']}\n" + firewall_rules(host)


def rule_host(content):
    match = re.match(re.escape(MARKER) + r"# Ports: (\d+),(\d+)\n", content.decode())
    if not match:
        raise ValueError("unrecognized native boundary rule file")
    host = {"http_port": int(match[1]), "https_port": int(match[2])}
    if content != rule_text(host).encode():
        raise ValueError("native boundary rules have been customized; preserve them for review")
    return host


def table_names(output):
    """A malformed listing is never evidence that our reserved table is absent."""
    def pairs(entries):
        result = {}
        for key, value in entries:
            if key in result:
                raise ValueError("duplicate firewall inspection key")
            result[key] = value
        return result

    def invalid_constant(value):
        raise ValueError("invalid firewall inspection constant")

    if not isinstance(output, str) or len(output) > 256 * 1024:
        raise ValueError("invalid firewall table inspection")
    value = json.loads(output, object_pairs_hook=pairs, parse_constant=invalid_constant)
    if not isinstance(value, dict) or set(value) != {"nftables"} or not isinstance(value["nftables"], list):
        raise ValueError("invalid firewall table inspection")
    tables = set()
    for entry in value["nftables"]:
        if not isinstance(entry, dict) or len(entry) != 1:
            raise ValueError("invalid firewall table inspection")
        kind, data = next(iter(entry.items()))
        if kind not in {"metainfo", "table"} or not isinstance(data, dict):
            raise ValueError("invalid firewall table inspection")
        if kind == "metainfo":
            continue
        family, name = data.get("family"), data.get("name")
        if (family not in {"ip", "ip6", "inet", "arp", "bridge", "netdev"}
                or not isinstance(name, str) or not name or (family, name) in tables):
            raise ValueError("invalid firewall table inspection")
        tables.add((family, name))
    return tables


def unit_text() -> str:
    return (MARKER + "[Unit]\nDescription=Thermite native listener boundary\n"
            "Before=thermite-openhab.service\nAfter=nftables.service firewalld.service\n"
            "[Service]\nType=oneshot\nRemainAfterExit=yes\n"
            "ExecStart=/usr/bin/env nft -f /etc/thermite-native.nft\n"
            # Stopping Thermite never removes protection from a running JVM.
            "[Install]\nWantedBy=multi-user.target\n")


class NativeIngress(Step):
    title = "Native network boundary"
    always = True
    stop_on_failure = True

    def __init__(self, context):
        self.context = context

    def check(self, system):
        for path in (UNIT_FILE, RULE_FILE):
            if not system.safe_unit_parent(path.parent):
                return Check(False, "", f"unsafe native boundary directory: {path.parent}")
            if system.lexists(path):
                file = system.unit_file(path)
                if (file is None or file.uid != 0 or file.mode & 0o022 or not file.ancestors_trusted
                        or not file.content.startswith(MARKER.encode())
                        or path == UNIT_FILE and file.content != unit_text().encode()):
                    return Check(False, "", f"unrecognized native boundary file: {path}")
                if path == RULE_FILE:
                    try:
                        rule_host(file.content)
                    except ValueError as exc:
                        return Check(False, "", str(exc))
        origin = system.unit_origin(UNIT)
        if not origin.known or origin.load_state != "not-found" and (
                origin.fragment != str(UNIT_FILE) or origin.drop_ins or origin.transient or origin.source):
            return Check(False, "", "unrecognized native boundary service or overrides")
        return Check(False, "apply and verify the native-port firewall; keep all other firewall tables")

    def actions(self, system):
        return [Task("install persistent native-port rules and verify the active kernel rules", self.perform)]

    @staticmethod
    def kernel_hint(system):
        """Explain a failed probe without guessing that a usable kernel is broken."""
        kernel = system.kernel()
        if (system.stat(Path("/sys/module/nf_tables")) is None
                and all(system.stat(Path(root) / kernel) is None
                        for root in ("/usr/lib/modules", "/lib/modules"))):
            system.say(f"The running kernel ({kernel}) has no installed module tree and nf_tables is not loaded. "
                       "If the kernel was updated, reboot into the installed kernel, then rerun the same upgrade command. "
                       "A reboot alone does not complete an interrupted deployment.")

    def perform(self, system, *, probe=False):
        from oh_access.files import atomic_private, private_directory, read_private
        from oh_access.native_boundary import verify_firewall
        from oh_install import runner
        directory = private_directory(self.context.var / "native-boundary")
        rules, unit = directory / RULE_FILE.name, directory / UNIT
        previous_path = directory / "previous.nft"
        # Authenticate sudo through the normal runner before read-only capture.
        code = runner.perform(Command(("-v",), root=True, terminal=True), system, self.context.area)
        if code is None or code:
            return code or 1
        code, current = system.capture(("sudo", "-n", "nft", "--json", "list", "tables"), diagnostics=True)
        if code:
            system.say(f"Cannot inspect existing firewall tables (exit {code}); no boundary rules were changed.")
            self.kernel_hint(system)
            return 1
        try:
            occupied = ("inet", "thermite_native") in table_names(current)
            if occupied and not (system.lexists(UNIT_FILE) and system.lexists(RULE_FILE)):
                raise ValueError("an existing thermite_native firewall table has no managed boundary files; preserve it for review")
            if occupied:
                code, current = system.capture(("sudo", "-n", "nft", "--json", "list", "table", "inet", "thermite_native"), diagnostics=True)
                previous = system.unit_file(RULE_FILE)
                if code or previous is None:
                    raise ValueError("cannot inspect previous native firewall policy")
                try:
                    verify_firewall(current, rule_host(previous.content))
                except ValueError:
                    # Installation can stop after publishing the new file but
                    # before applying it. Only our retained exact prior policy
                    # can explain that live state; extra rules still fail.
                    verify_firewall(current, rule_host(read_private(previous_path)))
                else:
                    # A completed apply may have been interrupted before
                    # removing an older journal. Snapshot the policy actually
                    # running now before starting the next port transition.
                    if not probe:
                        atomic_private(previous_path, previous.content)
        except (ValueError, KeyError, TypeError, AttributeError, OSError) as exc:
            system.say(str(exc))
            return 1
        atomic_private(rules, rule_text(self.context.host).encode())
        code = runner.perform(Command(("nft", "--check", "--file", str(rules)), root=True, terminal=True),
                              system, self.context.area)
        if code is None or code:
            if code is not None:
                self.kernel_hint(system)
            return code or 1
        if probe:
            return 0
        atomic_private(unit, unit_text().encode())
        commands = [
            ("install", "-o", "root", "-g", "root", "-m", "0644", str(rules), str(RULE_FILE)),
            ("install", "-o", "root", "-g", "root", "-m", "0644", str(unit), str(UNIT_FILE)),
            ("systemctl", "daemon-reload"),
            ("systemctl", "enable", UNIT),
            ("systemctl", "restart", UNIT),
        ]
        for argv in commands:
            code = runner.perform(Command(argv, root=True, terminal=True), system, self.context.area)
            if code is None or code:
                return code or 1
        code, output = system.capture(("sudo", "-n", "nft", "--json", "list", "table", "inet", "thermite_native"), diagnostics=True)
        try:
            if code:
                raise ValueError("cannot inspect the active native firewall")
            verify_firewall(output, self.context.host)
        except ValueError as exc:
            system.say(str(exc))
            return 1
        previous_path.unlink(missing_ok=True)
        return 0


class NativeIngressPrerequisites(NativeIngress):
    """Prove firewall support before replacing units or stopping native writers."""
    title = "Native network prerequisites"

    def check(self, system):
        result = super().check(system)
        return result if result.problem else Check(False, "validate firewall access, ownership and rule support before stopping services")

    def actions(self, system):
        return [Task("inspect existing firewall policy and check the required rules without applying them",
                     lambda system: self.perform(system, probe=True))]
