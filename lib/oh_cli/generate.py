"""Generate conf/ from instance/devices.yaml, metrics/ from it and
instance/host.yaml, and deploy/'s systemd units from versions.json and
instance/host.yaml; never edit any of them by hand.

    thermite generate [--house FILE] [--conf DIR]
                     validate the house file, then write every file under
                     conf/, metrics/ and deploy/ that differs
    thermite generate --check [--house FILE] [--conf DIR]
                     validate, then exit 1 naming every file under conf/,
                     metrics/ or deploy/ that is stale, missing or not
                     generated
    thermite generate --prune
                     also remove the files an earlier generate wrote that
                     nothing generates now

Without --prune writing never deletes: a file under conf/ or metrics/, or
a unit in deploy/, that nothing generates is reported and makes the exit
status 1.
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path
from typing import cast

import oh_cli
import oh_deploy as deploy
import oh_integrations as integrations
import oh_metrics as metrics
import oh_render as render
from oh_cli import AREA
from oh_conf import House

DESCRIPTION = """\
Generate conf/ from the house file (instance/devices.yaml), metrics/ (the
Prometheus, blackbox_exporter, Grafana and exporter configuration, and the
dashboards) from the house file and the host file (instance/host.yaml), and
deploy/'s systemd units from versions.json and the host file. All three are
generated: change the house file, the host file, versions.json or lib/,
then run this; never edit conf/, metrics/ or deploy/ by hand.

It validates the house file first and writes nothing while it has a
problem. A name a device lists for an integration thermite does not have
yet is no problem and generates nothing: a note names each one. Writing
never deletes: a file under conf/ or metrics/, or a unit
in deploy/ (Music Assistant's, once the host file has no music:), that
nothing generates is reported and makes the exit status 1; --prune removes
such a file when it carries the generated header (an earlier generate
wrote it), lies in conf/html/remote/, which the remote page's copies fill
whole, or is the page entry's helper an earlier release generated
(conf/automation/js/node_modules/thermite-entry/), and only reports any
other.
"""

EXAMPLES = (
    ("thermite generate", "validate the house file, then write every file under conf/, metrics/ and deploy/ "
                          "that differs"),
    ("thermite generate --check", "change nothing; name every stale, missing or stray file"),
    ("thermite generate --prune", "write, and remove generated files nothing generates any more"),
)

NOTES = """\
exit status:
  0  conf/, metrics/ and deploy/ are what the house file, the host file and
     versions.json generate (with --check: and nothing was written)
  1  a file is stale or missing (with --check), or conf/, metrics/ or
     deploy/ holds a file nothing generates
  2  a wrong switch, or a house or host file that is missing, cannot be
     read or has a problem (nothing is generated)
"""


#: What a generated text file's opening comment says; --prune removes a
#: stray file that says it (or one in OWNED).
MARK = b"Generated by bin/thermite generate"


#: conf/ directories a feature writes whole and copies into unmarked (the
#: remote page's files): a file there nothing generates now is an earlier
#: generate's copy of a file a later release dropped. So is the runtime's
#: page entry helper (oh_entry), a binary every release wrote there until
#: the entry became the sandbox's alone: it carries no header, so without
#: this a conf/ that still holds it would be stray to every generate, and
#: --prune would only report it.
OWNED = ("html/remote/", "automation/js/node_modules/thermite-entry/")


def generated(path: Path) -> bool:
    """Whether a file opens with the generated header, so generate wrote it."""
    try:
        with open(path, "rb") as file:
            return MARK in file.read(512)
    except OSError:
        return False


def rendered(house: House, versions: dict, host: dict) -> tuple[dict[str, str | bytes], dict[str, str], dict[str, str]]:
    """What a house, the host facts and the versions generate, in memory:
    conf/'s files and metrics/'s by their path below it, and deploy/'s units
    by their path in the area. The conf agrees with the house, or this
    raises oh_render.Disagreement (build()'s own check)."""
    built = render.build(house, host=host, versions=versions)
    return built.render(), metrics.render(house, host, versions, conf=built), deploy.render_units(versions, host)


def stale_units(units: dict[str, str], root: Path) -> list[str]:
    return [name for name, text in units.items()
            if not (root / name).exists() or (root / name).read_text(encoding="utf-8") != text]


def main(argv: list[str] | None = None) -> int:
    parser = oh_cli.command("generate", DESCRIPTION, EXAMPLES, NOTES)
    mode = parser.add_mutually_exclusive_group()
    mode.add_argument("--check", action="store_true", help="change nothing; exit 1 if conf/, metrics/ or deploy/ is stale")
    mode.add_argument("--prune", action="store_true",
                      help="also remove files under conf/, metrics/ and deploy/ with the generated header, or in "
                           "conf/html/remote/ or conf/automation/js/node_modules/thermite-entry/, that nothing "
                           "generates now")
    oh_cli.add_house(parser)
    oh_cli.add_conf(parser)
    # deploy/'s and metrics/'s parent, so that the tests can write them somewhere else.
    parser.add_argument("--root", type=Path, default=AREA, help=argparse.SUPPRESS)
    arguments = parser.parse_args(argv)
    house = House.load(arguments.house)
    devices = len(house.devices)
    try:
        versions, host = deploy.load(AREA)
    except (OSError, ValueError) as exc:
        print(f"thermite generate: {exc}; nothing generated", file=sys.stderr)
        return 2
    files, monitoring, units = rendered(house, versions, host)
    root = arguments.root
    trees: list[tuple[Path, str, dict[str, str | bytes]]] = [
        (arguments.conf, arguments.conf.name, files),
        (root / "metrics", "metrics", cast("dict[str, str | bytes]", monitoring)),
    ]
    stale: list[str] = []
    missing: list[str] = []
    stray: list[tuple[str, str]] = []
    written: list[str] = []
    pruned: list[str] = []
    for directory, shown, tree in trees:
        if arguments.check:
            old, absent, extra = render.compare(directory, tree)
            for path in old:
                print(f"thermite generate: {shown}/{path} is stale; run bin/thermite generate", file=sys.stderr)
            for path in absent:
                print(f"thermite generate: {shown}/{path} is missing; run bin/thermite generate", file=sys.stderr)
            stale += old
            missing += absent
        else:
            old, absent, extra = render.compare(directory, tree)
            for path in sorted(old + absent):
                render.put(directory / path, tree[path])
                print(f"wrote {shown}/{path}")
                written.append(path)
        for path in extra:
            ours = generated(directory / path) or (directory == arguments.conf and path.startswith(OWNED))
            if ours and arguments.prune:
                (directory / path).unlink()
                print(f"removed {shown}/{path}")
                pruned.append(path)
            elif ours:
                stray.append((f"{shown}/{path}", "an earlier generate wrote it; thermite generate --prune removes it"))
            else:
                stray.append((f"{shown}/{path}", f"thermite generate writes {shown}/ whole; move the file out of "
                                                 f"{shown}/ or delete it"))
    if arguments.check:
        stale_unit_names = stale_units(units, root)
        for name in stale_unit_names:
            print(f"thermite generate: {name} is stale; run bin/thermite generate", file=sys.stderr)
    else:
        stale_unit_names = []
        written_units = stale_units(units, root)
        for name in written_units:
            target = root / name
            target.parent.mkdir(parents=True, exist_ok=True)
            target.write_text(units[name], encoding="utf-8")
            print(f"wrote {name}")
    # A share's mount unit is named after the share: one removed from host.yaml stays behind.
    shared = {f"deploy/{path.name}" for path in (root / "deploy").glob("share-*.mount")}
    for name in sorted((set(deploy.INSTALLED) | shared) - set(units)):
        if not (root / name).is_file():
            continue
        if generated(root / name) and arguments.prune:
            (root / name).unlink()
            if not any((root / name).parent.iterdir()) and (root / name).parent != root / "deploy":
                (root / name).parent.rmdir()
            print(f"removed {name}")
            pruned.append(name)
        elif generated(root / name):
            stray.append((name, "an earlier generate wrote it; thermite generate --prune removes it"))
        else:
            stray.append((name, "move the file out of deploy/ or delete it"))
    for path, why in stray:
        print(f"thermite generate: {path}: nothing generates it now; {why}", file=sys.stderr)
    # Valid, and rendered as nothing: said here, or a device would look set up.
    notes = [integrations.planned_text(device["id"], phase, name)
             for device in house.devices for phase, name in integrations.planned(cast(dict, device))]
    for note in notes:
        print(f"thermite generate: note: {note}", file=sys.stderr)
    count = len(files) + len(monitoring)
    summary = f"generate: {devices} devices, {count} files, {len(units)} unit files"
    if arguments.check:
        summary += (f", {len(stale)} stale, {len(missing)} missing, {len(stray)} stray, "
                    f"{len(stale_unit_names)} stale unit files")
    else:
        summary += (f", {len(written)} written, {len(stray)} stray, {len(written_units)} unit files written"
                    + (f", {len(pruned)} removed" if arguments.prune else ""))
    print(summary + (f", {len(notes)} note{'s' if len(notes) > 1 else ''}" if notes else ""))
    return 1 if stale or missing or stray or stale_unit_names else 0
