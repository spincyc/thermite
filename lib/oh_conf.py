"""The in-memory conf/ that bin/thermite generate builds, and its YAML emitter.

Integration modules (lib/oh_integrations/) and house-wide features
(lib/oh_features/) add Things, Items, pages, add-ons and files to a Conf;
lib/oh_render.py runs them and writes the result. Things and Items are data
(dicts); dump() turns them into openHAB YAML in one fixed style.
"""

from __future__ import annotations

import functools
import re
import textwrap
from dataclasses import dataclass, field
from pathlib import Path
from typing import NamedTuple

import yaml

import oh_inventory as inventory

LIB = Path(__file__).resolve().parent
RENDERED = "Generated by bin/thermite generate from instance/devices.yaml; do not edit."

#: The profile that keeps an Item on a read-write channel display-only.
GUARD_PROFILE = "transform:JS"
GUARD_NOTE = (
    "Phase 1 is observe-only. Items on read-write channels are display-only",
    "three ways: stateDescription readOnly (UIs render no control), autoupdate",
    "off (no predicted state), and a transform:JS profile with only",
    "toItemScript, which discards every command from the Item before it",
    "reaches the binding.",
)
GUARD_ADDON_WHY = "the transform:JS profile that keeps phase-1 Items display-only"

#: A rendered rule that talks to its devices itself, with no binding between,
#: holds RULE_SENDS once; oh_render.read_only() swaps it for RULE_SILENT, so
#: the rule still reads its devices but sends them no command.
RULE_SENDS = "const SEND = true;"
RULE_SILENT = "const SEND = false;"

ADDONS_CFG = "services/addons.cfg"
ADDONS_HEADER = (
    "Exactly the add-ons conf/ uses. openHAB applies these lists at every start",
    "and uninstalls any add-on of these kinds that is missing from them.",
    "(openHAB 3.0 removed the old `package = minimal|standard|expert` key; an",
    "empty or absent list now means nothing extra is installed.)",
)

#: Keys whose lists of scalars are written in flow style, `[a, b]`.
FLOW_KEYS = frozenset({"groups", "tags"})
SECTIONS = ("things", "items", "pages")
# Scalars YAML 1.2's core schema resolves to something other than a string.
# PyYAML speaks YAML 1.1 and openHAB parses with another library, so a plain
# scalar must be a string under both.
CORE_NON_STRING = re.compile(
    r"null|Null|NULL|~|true|True|TRUE|false|False|FALSE"
    r"|[-+]?[0-9]+|0o[0-7]+|0x[0-9a-fA-F]+"
    r"|[-+]?(\.[0-9]+|[0-9]+(\.[0-9]*)?)([eE][-+]?[0-9]+)?"
    r"|[-+]?\.(inf|Inf|INF)|\.nan|\.NaN|\.NAN")


class Addon(NamedTuple):
    """One add-on a module needs: its addons.cfg key, its id, and why."""

    kind: str
    name: str
    #: Rendered as a comment above the add-on's addons.cfg line.
    why: str = ""


# ---------------------------------------------------------------- emitter

@functools.lru_cache(maxsize=None)
def _plain(text: str, context: str) -> bool:
    """Whether `text` reads back as the same string written plain in `context`."""
    if not text or text != text.strip() or not text.isprintable() or CORE_NON_STRING.fullmatch(text):
        return False
    probe, expected = {
        "key": (f"{text}: x", {text: "x"}),
        "value": (f"k: {text}", {"k": text}),
        "item": (f"- {text}", [text]),
        "flow": (f"k: [{text}]", {"k": [text]}),
    }[context]
    try:
        return yaml.safe_load(probe) == expected
    except yaml.YAMLError:
        return False


def _double_quoted(text: str) -> str:
    out = []
    for char in text:
        if char in '"\\':
            out.append("\\" + char)
        elif char.isprintable():
            out.append(char)
        else:
            code = ord(char)
            out.append(f"\\x{code:02x}" if code < 0x100 else
                       f"\\u{code:04x}" if code < 0x10000 else f"\\U{code:08x}")
    return '"' + "".join(out) + '"'


def scalar(value: object, context: str = "value") -> str:
    """One YAML scalar: plain when that reads back unchanged, else quoted.

    `context` is where it goes: a mapping "key", a block mapping "value", a
    block sequence "item" or a "flow" sequence entry.
    """
    if value is None:
        return "null"
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, int):
        return str(value)
    if isinstance(value, float):
        if value != value:
            return ".nan"
        if value in (float("inf"), float("-inf")):
            return ".inf" if value > 0 else "-.inf"
        text = repr(value)
        # YAML 1.1 reads 1e+20 as a string; 1.0e+20 is a float in both versions.
        if "e" in text and "." not in text:
            mantissa, exponent = text.split("e")
            text = f"{mantissa}.0e{exponent}"
        return text
    text = str(value)
    if _plain(text, context):
        return text
    # Single quotes keep embedded JSON readable; they cannot escape anything.
    if '"' in text and "'" not in text and text.isprintable():
        return f"'{text}'"
    return _double_quoted(text)


def _is_scalar(value: object) -> bool:
    return not isinstance(value, (dict, list, tuple))


def _sequence(values: list | tuple, indent: int) -> list[str]:
    pad = " " * indent
    lines: list[str] = []
    for value in values:
        if isinstance(value, dict) and value:
            body = emit(value, indent + 2)
            lines += [f"{pad}- {body[0].lstrip()}", *body[1:]]
        elif isinstance(value, (list, tuple)) and value:
            lines += [f"{pad}-", *_sequence(value, indent + 2)]
        elif isinstance(value, dict):
            lines.append(f"{pad}- {{}}")
        elif isinstance(value, (list, tuple)):
            lines.append(f"{pad}- []")
        else:
            lines.append(f"{pad}- {scalar(value, 'item')}")
    return lines


def emit(mapping: dict, indent: int = 0) -> list[str]:
    """A block mapping as lines: flow lists for FLOW_KEYS, `{}` when empty."""
    pad = " " * indent
    lines: list[str] = []
    for key, value in mapping.items():
        name = scalar(key, "key")
        if isinstance(value, dict):
            lines += [f"{pad}{name}:", *emit(value, indent + 2)] if value else [f"{pad}{name}: {{}}"]
        elif isinstance(value, (list, tuple)):
            if not value:
                lines.append(f"{pad}{name}: []")
            elif key in FLOW_KEYS and all(map(_is_scalar, value)):
                lines.append(f"{pad}{name}: [{', '.join(scalar(v, 'flow') for v in value)}]")
            else:
                lines += [f"{pad}{name}:", *_sequence(value, indent + 2)]
        else:
            lines.append(f"{pad}{name}: {scalar(value)}")
    return lines


def comment(lines: tuple[str, ...] | list[str], mark: str = "#") -> list[str]:
    return [f"{mark} {line}" if line else mark for line in lines]


def dump(header: list[str] | tuple[str, ...], document: dict) -> str:
    """An openHAB YAML file: header comments, `version: 1`, then `document`.

    Each entry of things, items and pages is followed by a blank line.
    """
    lines = [*comment(header), "version: 1", ""]
    for section, entries in document.items():
        if not entries:
            continue
        if section in SECTIONS and isinstance(entries, dict):
            lines.append(f"{section}:")
            for name, body in entries.items():
                lines += [*emit({name: body}, 2), ""]
        else:
            lines += [*emit({section: entries}), ""]
    while lines and lines[-1] == "":
        lines.pop()
    return "\n".join(lines) + "\n"


def retarget(text: str, path: str, uid: str, change) -> str:
    """A file dump() wrote, with change(thing) applied to Thing `uid`; the
    header comments are kept."""
    lines = text.split("\n")
    start = lines.index("version: 1")
    document = yaml.safe_load(text) or {}
    thing = (document.get("things") or {}).get(uid)
    if thing is None:
        raise ValueError(f"{path} has no Thing {uid}")
    change(thing)
    body = dump((), {key: document.get(key) or {} for key in ("things", "items", "pages")})
    return "".join(line + "\n" for line in lines[:start]) + body


# ---------------------------------------------------------------- the house

class House:
    """The validated inventory, with the names every renderer shares."""

    def __init__(self, data: dict) -> None:
        self.data = data
        self.rooms: dict[str, dict] = data.get("rooms") or {}
        self.devices: list[dict] = list(data.get("devices") or [])
        self._counts: dict[str, int] = {}
        for device in self.devices:
            text = self._base_label(device)
            self._counts[text] = self._counts.get(text, 0) + 1

    @staticmethod
    def _base_label(device: dict) -> str:
        name, make, model = device.get("name"), device.get("make") or "", device.get("model") or ""
        what = model if not make or model.lower().startswith(make.lower()) else f"{make} {model}"
        if not name:
            return what or device["id"]
        if model.lower() in name.lower():
            return name
        return f"{name} ({what})"

    def label(self, device: dict) -> str:
        """The device's display name; ` (<id>)` is added when two would share one."""
        text = self._base_label(device)
        return f"{text} ({device['id']})" if self._counts.get(text, 0) > 1 else text

    def room_label(self, room: str) -> str:
        return inventory.room_label(self.data, room)


def uses(device: dict, phase: str, name: str) -> bool:
    """Whether the device lists integration `name` under controls.<phase>."""
    return name in ((device.get("controls") or {}).get(phase) or [])


# ---------------------------------------------------------------- Items and pages

#: Every comma in an option's label becomes this: openHAB has no escape for one.
LABEL_COMMA = " / "


def options_text(pairs) -> str:
    """The `options` of a state or command description, from (value, label)
    pairs; an empty or None label gives the bare value.

    openHAB splits the text at every comma, quoted or not, and each entry at
    its first "=" unless it is written "value"="label"
    (MetadataStateDescriptionFragmentProvider, MetadataCommandDescriptionProvider).
    So a comma in a label becomes LABEL_COMMA, an entry with "=" is written
    quoted, and a value that no form carries is a ValueError."""
    entries = []
    for value, label in pairs:
        value = str(value)
        label = re.sub(r"\s*,\s*", LABEL_COMMA, str(label or "")).strip()
        if not value or value != value.strip() or "," in value or '"="' in value + label:
            raise ValueError(f"option value {value!r} with label {label!r} cannot be written in openHAB's options")
        if "=" in value or "=" in label:
            entries.append(f'"{value}"="{label or value}"')
        else:
            entries.append(f"{value}={label}" if label else value)
    return ",".join(entries)


def parse_options(text: str) -> list[tuple[str, str | None]]:
    """(value, label) of every option in an `options` text, as openHAB reads it."""
    out: list[tuple[str, str | None]] = []
    for entry in text.split(","):
        entry = entry.strip()
        if "=" not in entry:
            out.append((entry, None))
        elif entry.startswith('"') and '"="' in entry and entry.endswith('"'):
            value, label = entry[1:-1].split('"="')[:2]
            out.append((value.strip(), label.strip()))
        else:
            value, label = entry.split("=")[:2]
            out.append((value.strip(), label.strip()))
    return out


def point(device_id: str, type_: str, label: str, tags: list[str], channel: str, *,
          guarded: bool = False, fmt: str | None = None, icon: str | None = None) -> dict:
    """A point Item of a device's equipment group, linked to one channel.

    A guarded Item is display-only (GUARD_NOTE): it is how phase 1 links a
    read-write channel.
    """
    item: dict = {"type": type_, "label": label}
    if icon:
        item["icon"] = icon
    item["groups"] = [device_id]
    item["tags"] = list(tags)
    if fmt:
        item["format"] = fmt
    item["channel"] = channel
    return guard(item) if guarded else item


def linked(item: dict) -> list[str]:
    """The UIDs of every channel the Item is linked to, by `channel` or `channels`."""
    return ([item["channel"]] if item.get("channel") else []) + list(item.get("channels") or {})


def guard(item: dict) -> dict:
    """The Item, linked by `channel` or `channels`, made display-only
    (GUARD_NOTE): every link keeps only the state from its channel."""
    out = {key: value for key, value in item.items() if key not in ("format", "channel", "channels", "autoupdate")}
    out["autoupdate"] = False
    out["channels"] = {uid: {"profile": GUARD_PROFILE, "toItemScript": "|input"} for uid in linked(item)}
    metadata = item.get("metadata") or {}
    described = metadata.get("stateDescription") or {}
    config = dict(described.get("config") or {})
    if item.get("format"):
        config["pattern"] = item["format"]
    config["readOnly"] = True
    out["metadata"] = {**metadata, "stateDescription": {**described, "config": config}}
    return out


#: transform:JS link keys whose script passes an Item's commands to its channel
#: (toHandlerScript is openHAB's deprecated name for commandFromItemScript).
COMMAND_SCRIPTS = frozenset({"commandFromItemScript", "toHandlerScript"})


def is_guarded(item: dict) -> bool:
    """Whether a link of the Item discards every command (GUARD_NOTE); a
    transform:JS link with a COMMAND_SCRIPTS script passes them on."""
    return any((link or {}).get("profile") == GUARD_PROFILE and not COMMAND_SCRIPTS & set(link)
               for link in (item.get("channels") or {}).values())


def layout_page(label: str, columns: list[dict]) -> dict:
    """A Main UI layout page with one row of columns."""
    return {
        "component": "oh-layout-page",
        "config": {"label": label},
        "slots": {"default": [{
            "component": "oh-block", "config": {}, "slots": {"default": [{
                "component": "oh-grid-row", "config": {}, "slots": {"default": columns},
            }]},
        }]},
    }


def list_card_column(config: dict, title: str, entries: list[dict]) -> dict:
    """A grid column holding one list card."""
    return {
        "component": "oh-grid-col", "config": config,
        "slots": {"default": [{
            "component": "oh-list-card", "config": {"title": title},
            "slots": {"default": entries},
        }]},
    }


def label_item(item: str, title: str, **config: object) -> dict:
    return {"component": "oh-label-item", "config": {"item": item, "title": title, **config}}


# ---------------------------------------------------------------- the conf

@dataclass
class YamlFile:
    """One file under conf/yaml/: its header comment and its definitions."""

    header: tuple[str, ...]
    things: dict[str, dict] = field(default_factory=dict)
    items: dict[str, dict] = field(default_factory=dict)
    pages: dict[str, dict] = field(default_factory=dict)

    @property
    def guarded(self) -> bool:
        return any(map(is_guarded, self.items.values()))

    def text(self) -> str:
        header = [RENDERED, "", *self.header, *(GUARD_NOTE if self.guarded else ())]
        return dump(header, {"things": self.things, "items": self.items, "pages": self.pages})


class Conf:
    """Everything bin/thermite generate writes, keyed by path under conf/."""

    def __init__(self) -> None:
        self.yaml: dict[str, YamlFile] = {}
        self.files: dict[str, str | bytes] = {}
        self.addons: dict[str, dict[str, list[str]]] = {}

    def yaml_file(self, path: str, header: tuple[str, ...] | list[str]) -> YamlFile:
        if path not in self.yaml:
            self.yaml[path] = YamlFile(tuple(header))
        return self.yaml[path]

    def add_addon(self, addon: Addon) -> None:
        reasons = self.addons.setdefault(addon.kind, {}).setdefault(addon.name, [])
        if addon.why and addon.why not in reasons:
            reasons.append(addon.why)

    def add_asset(self, path: str, source: Path) -> None:
        """Copy a file kept beside its module, headed by where it came from."""
        mark = "//" if source.suffix == ".js" else "#"
        origin = source.resolve().relative_to(LIB.parent)
        self.files[path] = (f"{mark} Copied by bin/thermite generate from {origin}; do not edit.\n"
                            + source.read_text(encoding="utf-8"))

    def add_web_file(self, path: str, source: Path) -> None:
        """Copy a file byte for byte: a web manifest or an image has no room for a header."""
        self.files[path] = source.read_bytes()

    def item(self, name: str) -> dict | None:
        """The Item called `name`, from whichever file defines it."""
        return next((file.items[name] for file in self.yaml.values() if name in file.items), None)

    def points(self, device_id: str) -> list[tuple[str, dict]]:
        """(name, Item) of every Item in the device's equipment group, in file order."""
        return [(name, item) for file in self.yaml.values() for name, item in file.items.items()
                if device_id in (item.get("groups") or [])]

    @property
    def guarded(self) -> bool:
        return any(file.guarded for file in self.yaml.values())

    def addons_cfg(self) -> str:
        lines = comment([RENDERED, "", *ADDONS_HEADER])
        for kind in sorted(self.addons):
            names = self.addons[kind]
            lines.append("")
            for name in sorted(names):
                if names[name]:
                    why = f"{name}: {' and '.join(names[name])}."
                    lines += comment(textwrap.wrap(why, 76, break_on_hyphens=False))
            lines.append(f"{kind} = {','.join(sorted(names))}")
        return "\n".join(lines) + "\n"

    def render(self) -> dict[str, str | bytes]:
        """Path under conf/ -> content (bytes for a file copied byte for byte), for every file."""
        out = {path: file.text() for path, file in self.yaml.items()}
        if self.addons:
            out[ADDONS_CFG] = self.addons_cfg()
        out.update(self.files)
        return dict(sorted(out.items()))
