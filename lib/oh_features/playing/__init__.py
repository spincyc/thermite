"""What each device plays: the app on its screen and the title, as its
integrations report them (playing() in oh_integrations), as two Items per
device:

- `<id>_playing_app` (String): the app's name, such as Disney+;
- `<id>_playing_title` (String): the title, such as "DuckTales S2E5 ·
  Woo-oo!", or a track and its artist.

Each reads UNDEF while nothing plays, or nothing names it. Both are free
text: a Guest sees them only while an Admin lets Guests see titles
(oh_identity.security.guests_see_text).

conf/automation/js/playing.js, playing.js beside this file with TABLE filled
in, sets them whenever what it reads changes. The app is the first app
Item's that names one; the title the first title Item's whose `when` holds.
A device whose power Item reads OFF, or whose app is idle (a home screen,
the screen saver), plays nothing. A value that goes away is kept HOLD_MS,
as a cast session drops its title for a moment when an advert starts or the
player seeks; a new value shows at once. A new app ends the last one's
title at once (playing.js).

The remotes show what a room's source plays (oh_features.remote_model), and
the exporter keeps it as thermite_playing_timestamp_seconds (oh_metrics),
for as long as the house keeps its metrics.
"""

from __future__ import annotations

import json
from pathlib import Path

import oh_integrations as integrations
from oh_conf import Addon, Conf, House, uses

NAME = "playing"
ITEMS = "yaml/playing.yaml"
RULE = "automation/js/playing.js"
SOURCE = Path(__file__).resolve().parent / "playing.js"
MARK = "const TABLE = null;"
ITEM_ONLY_RULES = (RULE,)
#: Milliseconds a value that goes away is kept.
HOLD_MS = 15000
#: Characters of an app or title kept, under the gateway's bound for free
#: text (oh_site_contract.TEXT).
MAX_TEXT = 160
HEADER = (
    "What each device plays (lib/oh_features/playing): its app and title, as",
    "conf/automation/js/playing.js joins them from its integrations' Items.",
)


def declarations(device: dict) -> list[dict]:
    """What each of the device's integrations reads of what it plays."""
    found = []
    for module in integrations.REGISTRY:
        if callable(getattr(module, "playing", None)) and uses(device, module.PHASE, module.NAME):
            spec = module.playing(device)
            if spec:
                found.append(spec)
    return found


def items(device: dict) -> dict | None:
    """The device's two Items, {"app", "title"}; None when nothing tells
    what it plays."""
    if not declarations(device):
        return None
    return {"app": f"{device['id']}_playing_app", "title": f"{device['id']}_playing_title"}


def validate(data: dict) -> list[str]:
    return []


def entry(device: dict) -> dict:
    """The rule's row for a device: its integrations' reads joined, in
    REGISTRY order, but an Android package (the app on screen) first: the
    first app Item with a value says whether anything plays, and a cast
    session can name its screen saver while the app plays on."""
    specs = declarations(device)
    names = items(device)
    apps = [dict(source) for spec in specs for source in spec.get("apps", ())]
    return {"id": device["id"], "app": names["app"], "title": names["title"],
            "power": next((spec["power"] for spec in specs if spec.get("power")), None),
            "apps": sorted(apps, key=lambda source: not source.get("package")),
            "titles": [dict(source) for spec in specs for source in spec.get("titles", ())]}


def table(house: House) -> dict:
    return {"holdMs": HOLD_MS, "maxText": MAX_TEXT,
            "devices": [entry(device) for device in house.devices if items(device)]}


def rule(house: House) -> str:
    source = SOURCE.read_text(encoding="utf-8")
    if source.count(MARK) != 1:
        raise ValueError(f"{SOURCE} must contain the line {MARK!r} exactly once")
    origin = SOURCE.relative_to(SOURCE.parents[3])
    header = (f"// Generated by bin/thermite generate from {origin} and\n"
              "// instance/devices.yaml; do not edit.\n")
    return header + source.replace(MARK, "const TABLE = " + json.dumps(table(house), indent=1) + ";")


def render(house: House, conf: Conf) -> None:
    devices = [device for device in house.devices if items(device)]
    if not devices:
        return
    out = conf.yaml_file(ITEMS, HEADER)
    for device in devices:
        names = items(device)
        for key, label, tags in (("app", "Playing App", ["Status", "App"]), ("title", "Playing", ["Status", "Info"])):
            out.items[names[key]] = {"type": "String", "label": label, "groups": [device["id"]], "tags": tags}
    conf.files[RULE] = rule(house)
    conf.add_addon(Addon("automation", "jsscripting", "the playing rule (playing.js)"))
