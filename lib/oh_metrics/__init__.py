def render(house: House, host: dict, versions: dict | None = None, *, conf=None) -> dict[str, str]:
    """Path under metrics/ -> text, for every file metrics/ must hold; `conf`
    is the house's oh_render.build(), when the caller has built it already."""
    conf = conf if conf is not None else _build(house)
    mapping = exporter_map(house, conf)
    found, _ = probes(house, conf)
    prometheus = prometheus_yml(house, host, conf)
    files = {
        PROMETHEUS_YML: prometheus,
        BLACKBOX_YML: blackbox_yml(),
        "prometheus/alerts.yml": _yaml([RENDERED], alerts.rules(mapping)),
        GRAFANA_INI: grafana_ini(host),
        GRAFANA_DATASOURCE: grafana_datasource(host, versions),
        GRAFANA_PROVIDER: grafana_provider(),
        EXPORTER_MAP: _json(mapping),
    }
    for name, board in dashboards.render(mapping, [dataclasses.asdict(p) for p in found],
                                         yoke_enabled=bool(yoke_targets(host)),
                                         targets=scrape_targets(prometheus)).items():
        files[f"{GRAFANA_DASHBOARDS}/{name}.json"] = _json(board)
    return dict(sorted(files.items()))


