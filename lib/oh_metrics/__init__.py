@dataclasses.dataclass(frozen=True)
class Probe:
    """One TCP probe of a device's control port."""

    device: str
    room: str
    kind: str
    address: str
    port: int
    integrations: tuple[str, ...]

    @property
    def target(self) -> str:
        return f"{self.address}:{self.port}"


def _uses(device: dict, phase: str, name: str) -> bool:
    return name in ((device.get("controls") or {}).get(phase) or [])


def _integrations(device: dict) -> list[str]:
    """Every integration the device lists, observe first, without repeats."""
    controls = device.get("controls") or {}
    return list(dict.fromkeys([*(controls.get("observe") or []), *(controls.get("control") or [])]))


def thing_ports(thing: dict) -> list[int]:
    """The TCP ports a Thing's configuration talks to: its baseURL's and
    every `port` or `...Port` setting."""
    config = thing.get("config") or {}
    found: list[int] = []
    url = config.get("baseURL")
    if isinstance(url, str) and "://" in url:
        split = urllib.parse.urlsplit(url)
        default = {"http": 80, "https": 443}.get(split.scheme)
        port = split.port or default
        if port:
            found.append(port)
    for key, value in sorted(config.items()):
        if (key == "port" or key.endswith("Port")) and isinstance(value, int) and not isinstance(value, bool):
            found.append(value)
    return found


def thing_device(uid: str) -> str:
    """The device a generated Thing is named after: the last segment of its
    UID (oh_inventory.cross_check() holds conf/ to that)."""
    return uid.split(":")[-1]


def device_things(conf, ident: str) -> list[tuple[str, str]]:
    """(Thing UID, its conf/ file) of every Thing generated for a device, a
    ping Thing included: whether a Thing's status says anything of the
    device is signals()'s to say."""
    return [(uid, path) for path, file in sorted(conf.yaml.items()) for uid in file.things
            if thing_device(uid) == ident]


def _build(house: House):
    # Imported here: oh_render needs PyYAML and the integrations, which the
    # exporter (this package, in the helper's image) must not.
    import oh_render

    return oh_render.build(house)


def probes(house: House, conf=None) -> tuple[list[Probe], list[tuple[str, tuple[str, ...]]]]:
    """(TCP probes, (device, integrations) with an address but no port found)."""
    import oh_integrations

    conf = conf if conf is not None else _build(house)
    found: list[Probe] = []
    unknown: list[tuple[str, tuple[str, ...]]] = []
    for device in house.devices:
        if not device.get("ip"):
            continue
        ident = device["id"]
        by_port: dict[int, list[str]] = {}
        for module in oh_integrations.REGISTRY:
            phases = [module.PHASE] + (["control"] if module.CONTROL else [])
            if not any(_uses(device, phase, module.NAME) for phase in phases) or not module.PROBED:
                continue
            numbers: list[int] = []
            if module.PORT is not None:
                numbers.append(module.PORT)
            file = conf.yaml.get(module.FILE)
            for uid, thing in sorted((file.things if file else {}).items()):
                if thing_device(uid) == ident:
                    numbers += thing_ports(thing)
            numbers += module.PROBE_PORTS
            for number in numbers:
                names = by_port.setdefault(number, [])
                if module.NAME not in names:
                    names.append(module.NAME)
        if not by_port:
            unknown.append((ident, tuple(_integrations(device))))
            continue
        for number in sorted(by_port):
            found.append(Probe(ident, device["room"], device["kind"], device["ip"], number,
                               tuple(sorted(by_port[number]))))
    return found, unknown


@dataclasses.dataclass(frozen=True)
class Signal:
    """One reading that says whether a device answers."""

    #: What it reads (signals()): thing, port, reads or online.
    kind: str
    #: The integrations it reads the device through.
    integrations: tuple[str, ...]
    metric: str
    labels: tuple[tuple[str, str], ...]
    #: The value that says the device does not answer.
    bad: int
    #: A control check is built on it (health_paths()): it is of an
    #: integration the device lists under control, no ROUTE_OPTIONAL one,
    #: and no ping.
    control: bool


def signals(device: dict, conf, found: list[Probe]) -> list[Signal]:
    """Every reading that says whether `device` answers, from the generated
    configuration `conf` and its probes `found` (probes()).

    The one derivation: health_paths() builds a device's availability checks
    from these, and unobserved() names what these leave unread, so that a
    device cannot be commanded and unwatched without generation saying so.

    thing   the status of a Thing of an integration the device lists: one
            whose UID ends in the device's id, or the one the integration
            sends the device's commands through (its transport() hook: a
            source's CEC goes through a Thing named after the matrix). Not
            of an integration whose Things do not follow the device
            (THING_FOLLOWS_DEVICE: a ping Thing is ONLINE while nothing
            answers)
    port    a control port probed over TCP
    reads   what an integration's own rule meets reading the device (READS),
            where the rule keeps a tally for it
    online  the device's `<id>_online`: whether it answers a ping, or its
            controller's word. A reading and never a check: a device that
            sleeps answers no ping, and one that answers a ping and not its
            control port fails the check of that port, Thing or read
    """
    import oh_integrations
    from oh_integrations import _commands

    ident = device["id"]
    listed = _integrations(device)
    needed = set((device.get("controls") or {}).get("control") or []) - {
        module.NAME for module in oh_integrations.REGISTRY if module.ROUTE_OPTIONAL}
    present = {name for file in conf.yaml.values() for name in file.items}
    out: list[Signal] = []
    for module in oh_integrations.REGISTRY:
        if module.NAME not in listed:
            continue
        file = conf.yaml.get(module.FILE)
        things = [uid for uid in (file.things if file else {}) if thing_device(uid) == ident]
        through = module.transport(device) if module.transport else None
        if through and file and through in file.things and through not in things:
            things.append(through)
        control = module.NAME in needed
        if module.THING_FOLLOWS_DEVICE:
            out += [Signal("thing", (module.NAME,), "thermite_thing_online", (("thing", uid),), 0, control)
                    for uid in things]
        if module.READS and _commands.tally_item(ident, module.NAME) in present:
            out.append(Signal("reads", (module.NAME,), "thermite_device_read_ok",
                              (("device", ident), ("integration", module.NAME)), 0, control))
        if file and f"{ident}_online" in file.items:
            out.append(Signal("online", (module.NAME,), "thermite_item_value",
                              (("item", f"{ident}_online"), ("point", "online")), 0, False))
    out += [Signal("port", probe.integrations, "probe_success",
                   (("job", DEVICE_JOB), ("device", ident), ("port", str(probe.port))), 0,
                   bool(needed.intersection(probe.integrations)))
            for probe in found if probe.device == ident]
    return out


#: Each kind of signal as a person reads it: what it is a reading of (with
#: the signal's own labels), and its words while the device answers and
#: while it does not. A kind signals() gives has its words here.
SIGNAL_WORDS = {
    "thing": ("Thing {thing}", "ONLINE", "not ONLINE"),
    "port": ("TCP port {port}", "accepts connections", "closed, or nothing answers there"),
    "reads": ("{integration}'s own reads of it", "it answers", "it cannot be read"),
    "online": ("Ping, or its controller's word", "it answers", "no response"),
}


def signal_words(signal: Signal) -> tuple[str, str, str]:
    """(what `signal` reads, its words while the device answers, its words
    while it does not), for a person."""
    subject, well, bad = SIGNAL_WORDS[signal.kind]
    return subject.format(**dict(signal.labels)), well, bad


def unobserved(house: House, conf=None) -> list[tuple[str, str]]:
    """What generation must name, since no reading would ever say that it
    stopped answering: (device, integration) for an integration a device
    lists under control with no signal of its own (signals()), and
    (device, "") for a device with an address and no signal at all.
    `thermite check house` prints each, and prometheus.yml's header lists them."""
    conf = conf if conf is not None else _build(house)
    found, _ = probes(house, conf)
    out: list[tuple[str, str]] = []
    for device in house.devices:
        read = signals(device, conf, found)
        through = {name for signal in read for name in signal.integrations}
        missing = [name for name in (device.get("controls") or {}).get("control") or [] if name not in through]
        out += [(device["id"], name) for name in dict.fromkeys(missing)]
        if not read and not missing and device.get("ip"):
            out.append((device["id"], ""))
    return out


def unobserved_text(device: str, integration: str) -> str:
    """One finding of unobserved(), as a person reads it."""
    import oh_integrations
    if integration in oh_integrations.PLANNED["control"]:
        # Not a reading that is missing: nothing was rendered to read.
        return oh_integrations.planned_text(device, "control", integration)
    if integration:
        return (f"{device}: nothing reads whether it answers {integration}: no Thing, probed port or read of the "
                "rule's own says so, and no check or alert can")
    return (f"{device}: it has an address and nothing reads whether it answers; list network_ping under its "
            "controls.observe to have it pinged")


def _options(item: dict) -> list[str] | None:
    """The values a String Item's state or command description offers."""
    import oh_conf
    metadata = item.get("metadata") or {}
    values: list[str] = []
    for key in ("stateDescription", "commandDescription"):
        text = ((metadata.get(key) or {}).get("config") or {}).get("options")
        if isinstance(text, str) and text:
            for value, _ in oh_conf.parse_options(text):
                if value and value not in values:
                    values.append(value)
    return values or None


#: The property tag of a kept Measurement -> its point.
MEASURED = {"Temperature": "temperature", "StateOfCharge": "battery"}


def select_point(name: str, item: dict) -> tuple[str, str] | None:
    """(point, conversion) of an Item of a device worth keeping, else None.

    Kept: the device's problem text (`<id>_problem`, as 0/1), and every
    Item tagged with the property Power, SoundVolume or Channel (power,
    power state, volume, mute, input), plus the Number Items a matrix or
    switch is commanded with (routing), a Number measuring a device's
    temperature or a battery's charge (MEASURED), and `<id>_online` (point
    online): whether the device answers a ping, or its controller reports
    it connected. A ping Thing's status does not say that: it is ONLINE
    while nothing answers (THING_FOLLOWS_DEVICE). A speaker's playing state
    is kept too, from its audio page (exporter_map() `playing` points).
    Not kept: EDID selections (fixed settings), titles, artists and apps
    (what a device plays is kept once, joined, as
    thermite_playing_timestamp_seconds: exporter_map() `playing`), and keys
    and pairing Items (no state worth a history).
    """
    kind = str(item.get("type") or "").split(":")[0]
    tags = set(item.get("tags") or [])
    if kind == "String" and name.endswith("_problem"):
        return "problem", "problem"
    if kind == "Switch" and name.endswith("_online"):
        return "online", "switch"
    if "Power" in tags:
        return {"Switch": ("power", "switch"), "String": ("power_state", "enum")}.get(kind)
    if "SoundVolume" in tags:
        return {"Switch": ("mute", "switch"), "Dimmer": ("volume", "number"),
                "Number": ("volume", "number")}.get(kind)
    if "Channel" in tags:
        return {"String": ("input", "enum"), "Number": ("input", "number")}.get(kind)
    if kind == "Number" and "Control" in tags:
        return None if name.endswith("_edid") else ("routing", "number")
    if kind == "Number" and "Measurement" in tags:
        return next(((point, "number") for tag, point in MEASURED.items() if tag in tags), None)
    return None


def exporter_map(house: House, conf=None) -> dict:
    """The exporter's map: every device with its Things (those whose status
    follows the device: not a ping Thing), and every Item kept
    (select_point()) with how its state becomes a number, plus each room's
    Source selector and each speaker's playing state: the state Item of its
    audio page (oh_integrations audio(), as the remotes' Listen reads it),
    with the page's playing values and its title Item, which tell a track
    from TV audio or line-in (exporter PLAYING_TRACK), its silent reading,
    which tells TV audio from a silent TV, the routes that feed it a
    picture alone (remote_model.quiet_routes()), and its multiroom group's
    Items (oh_integrations group()), by which a follower plays what its
    leader plays."""
    import oh_integrations
    from oh_integrations import _commands
    from oh_features import remote_model

    conf = conf if conf is not None else _build(house)
    # A ping Thing is ONLINE while nothing answers its address: as a
    # device's Thing it made a dead device read online.
    mute = {module.FILE for module in oh_integrations.REGISTRY if not module.THING_FOLLOWS_DEVICE}
    things: dict[str, list[str]] = {}
    for path, file in conf.yaml.items():
        for uid in ([] if path in mute else file.things):
            things.setdefault(thing_device(uid), []).append(uid)
    devices: dict[str, dict] = {}
    items: dict[str, dict] = {}
    present = {name for file in conf.yaml.values() for name in file.items}
    for device in house.devices:
        ident = device["id"]
        devices[ident] = {"room": device["room"], "kind": device["kind"], "label": house.label(device),
                          "things": sorted(things.get(ident, [])),
                          **({"optional": True} if device.get("monitor") == "optional" else {})}
        kept: dict[str, dict] = {}
        for name, item in conf.points(ident):
            chosen = select_point(name, item)
            if chosen is None:
                continue
            point, convert = chosen
            entry = {"device": ident, "room": device["room"], "kind": device["kind"], "point": point,
                     "convert": convert}
            # A device's problem Item holds a problem code, or CLEAR for
            # "nothing wrong" (oh_integrations._commands); other undefined
            # telemetry remains unknown. Missing/NULL is not clear.
            if point == "problem" and name == _commands.problem_item(ident):
                entry["clear_state"] = _commands.CLEAR
                # Its codes, so that the one it holds can be a bounded label
                # (thermite_device_problem_info).
                entry["options"] = _options(item)
            if convert == "enum":
                entry["options"] = _options(item)
            items[name] = kept[name] = entry
        # The power Item each reading needs on, so that a reading with no
        # value while it reads OFF is the device being off, not unknown.
        # Whether it answers a ping needs nothing on.
        for name, power in oh_integrations.powered(device, dict(conf.points(ident))).items():
            if name in kept and power in kept and kept[name]["point"] != "online":
                kept[name]["power"] = power
        page = remote_model.audio_page(device) or {}
        state, title = page.get("state") or {}, (page.get("track") or {}).get("title")
        silent = state.get("silent") or {}
        points = dict(conf.points(ident))
        routes = [{key: route[key] for key in ("item", "is", "input") if key in route}
                  for route in remote_model.quiet_routes(house, ident)
                  if route["item"] in present and ("input" not in route or route["input"]["item"] in points)]
        grouped = next((found for module in oh_integrations.defining("group") if (found := module.group(device))),
                       None) or {}
        if state.get("item") in points and state.get("playing"):
            items[state["item"]] = {"device": ident, "room": device["room"], "kind": device["kind"], "point": "playing",
                                    "convert": "playing", "playing": [str(value) for value in state["playing"]],
                                    **({"title": title} if title in points else {}),
                                    **({"silent": {"item": silent["item"], "is": [str(value) for value in silent["is"]]}}
                                       if silent.get("item") in points else {}),
                                    **({"route": routes} if routes else {}),
                                    **({"group": {key: grouped[key] for key in ("id", "leader")}}
                                       if grouped and {grouped["id"], grouped["leader"]} <= set(points) else {})}
    for file in conf.yaml.values():
        for name, item in file.items.items():
            groups = item.get("groups") or []
            if (name.startswith("loc_") and name.endswith("_source") and item.get("type") == "String"
                    and groups and str(groups[0]).startswith("loc_")):
                # The routing zone (routing.item_name()), which the exporter
                # adds to the Item's series: a room may have two zones.
                items[name] = {"device": "", "room": str(groups[0])[4:],
                               "zone": name.removeprefix("loc_").removesuffix("_source"), "kind": "",
                               "point": "source", "convert": "enum", "options": _options(item)}
    rooms = {room: house.room_label(room) for room in house.rooms}
    paths, checks = health_paths(house, conf, items)
    # Each routed source as the remotes name it (routing.sources.<id>.label).
    sources = {ident: str(entry["label"]) for ident, entry in
               ((house.data.get("routing") or {}).get("sources") or {}).items()
               if isinstance(entry, dict) and entry.get("label")}
    # Each device's playing Items (oh_features.playing), which the exporter
    # keeps as thermite_playing_timestamp_seconds.
    from oh_features import playing
    shown = {device["id"]: names for device in house.devices
             if (names := playing.items(device)) and set(names.values()) <= present}
    result = {"version": MAP_VERSION, "rooms": rooms, "devices": devices, "sources": sources,
              "items": dict(sorted(items.items())), "paths": paths, "health_checks": checks, "playing": shown}
    # Each script's tally of the commands it took for a device, which the
    # exporter turns into thermite_device_commands_total.
    tallies = _commands.tallies(house.devices, present)
    if tallies:
        result["commands"] = dict(sorted(tallies.items()))
    from oh_features import threadpools
    if threadpools.enabled(house):
        result["handler_pool"] = dict(threadpools.ITEM_NAMES)
    routing = routing_map(house, conf, items, paths)
    if routing:
        result["routing"] = routing
    return result


def routing_map(house: House, conf, items: dict, paths: dict) -> dict:
    """The routing executor's status Item and the routing telemetry Item,
    when the house has them, with each routing zone's room and label and
    the devices the executor commands (each executor actor's key): the
    exporter turns their JSON into thermite_routing_* and
    thermite_route_seconds, with a zero for every zone and executor device
    routing has not counted yet, and writes thermite_zone_info."""
    from oh_features import routing
    from oh_features.routing import lifecycle_io

    present = {name for file in conf.yaml.values() for name in file.items}
    zones = {spec["zone"]: {
                 "room": spec["room"], "label": (paths.get(name) or {}).get("label") or house.room_label(spec["room"])}
             for name, spec in items.items() if spec.get("point") == "source"}
    found = {key: name for key, name in (("status", lifecycle_io.STATUS_ITEM), ("metrics", routing.METRICS_ITEM))
             if name in present}
    if not found:
        return {}
    capabilities = lifecycle_io.capabilities(house.devices) if conf.executor_controls else {}
    executors = sorted({capabilities[item]["key"] for item in conf.executor_controls if item in capabilities})
    # routing.js's deadline (RECENT_MS): a choice its readback has not shown
    # by then counts as `deadline`.
    deadline = routing.hold_ms(house) / 1000
    return {**found, "zones": dict(sorted(zones.items())), "executors": executors,
            "deadline_seconds": int(deadline) if deadline.is_integer() else deadline}


def health_paths(house: House, conf, items: dict) -> tuple[dict, list[dict]]:
    """Required control checks from the same physical paths as Signal / Audio.

    Membership is per source, not room: local display sources bypass the
    receiver and matrices, and a room's `audio` device (the one its Volume
    and Mute drive) joins every source whose signal carries sound, not one
    that carries a picture alone (routing's carries). Only control
    integrations supply availability checks; an optional Cast observer
    cannot invalidate working Sony control. A check reads what holds now,
    and which readings those are is signals()'s to say: a Thing's status, a
    probed port, what a rule's own reads of the device meet. The device's
    problem Item is none: it keeps the problem of a command until the
    device takes one (oh_integrations._commands), so it would fail a check
    for as long as nobody commands the device again.
    Infrastructure serving routing is monitored even when every zone is Off.
    A speaker (a `playing` point, exporter_map()) is in use while it plays,
    or did within alerts.IN_USE: its demand is {"item": its playing Item,
    "playing": True}.
    Each check names its device and what it checks (CHECKS); a device marked
    `monitor: optional` in the house file is shown but never required. The
    exporter ignores these map fields: alerts.rules() records them as
    thermite:check.
    """
    from oh_features import remote_diagnostics, routing

    devices = house.by_id
    physical = remote_diagnostics.manifest(house, conf)["rooms"]
    found, _ = probes(house, conf)
    checks: dict[tuple, dict] = {}

    def add(name: str, device: str, metric: str, labels: dict, bad: int, demand: dict | None) -> None:
        key = (metric, tuple(sorted(labels.items())), bad)
        check = checks.setdefault(key, {"metric": metric, "labels": labels, "bad": bad, "device": device,
                                       "check": name, "always": False, "required": [],
                                       "optional": devices[device].get("monitor") == "optional"})
        if demand is None:
            check["always"] = True
        elif demand not in check["required"]:
            check["required"].append(demand)

    def device_checks(ident: str, demand: dict | None, node: dict | None = None) -> None:
        device = devices[ident]
        # The readings of the integrations that command it. An optional
        # transport (ROUTE_OPTIONAL) remains observable without invalidating
        # a source's working power/input path when it is down, and a ping
        # is a reading only (signals()). The problem Item is none of them: a
        # command's problem stays there until the device takes a command,
        # long after its cause went.
        for signal in signals(device, conf, found):
            if signal.control:
                add(signal.kind, ident, signal.metric, dict(signal.labels), signal.bad, demand)
        if demand is None:
            return
        power = []
        if node and node["role"] in ("receiver", "display") and (module := routing.stager(device)):
            zone = node.get("zone")
            stage = module.stage(device, None if zone == "main" else zone)
            power = [stage["power"]] if stage else []
        elif node and node["role"] == "source":
            power = [name for name, s in items.items() if s.get("device") == ident and s.get("point") == "power"]
        for name in power:
            if name in items:
                add("power", ident, "thermite_item_value", {"item": name, "point": "power"}, 0, demand)

    routed = (house.data.get("routing") or {}).get("rooms") or {}
    paths = {}
    for zone, entry in physical.items():
        name = routing.item_name(zone)
        paths[name] = {"zone": zone, "label": entry["label"], "sources": {}}
        # The device the room's Volume and Mute drive (routing.rooms.<id>.audio)
        # is in use with every source that carries sound, though no signal
        # passes through it.
        audio = (routed.get(zone) or {}).get("audio")
        for source, path in entry["sources"].items():
            nodes = path["nodes"] + path.get("audioNodes", [])
            used = paths[name]["sources"][source] = list(dict.fromkeys(n["device"] for n in nodes))
            for node in nodes:
                device_checks(node["device"], {"item": name, "source": source}, node)
            if audio in devices and audio not in used and path.get("carries") != "display":
                used.append(audio)
                device_checks(audio, {"item": name, "source": source})
    for ident, device in devices.items():
        if device.get("kind") in ("hdmi_matrix", "usb_matrix", "hdmi_switch"):
            device_checks(ident, None)
    for name, spec in sorted(items.items()):
        if spec.get("point") == "playing":
            device_checks(spec["device"], {"item": name, "playing": True})
    return paths, list(checks.values())


