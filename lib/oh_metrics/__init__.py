"""Metrics and dashboards for the house: the tree bin/thermite generate writes
to metrics/ from instance/devices.yaml and instance/host.yaml.

metrics/ is local derived output like conf/: Git ignores it and nobody edits
it by hand. It holds the Prometheus scrape configuration
(prometheus/prometheus.yml), the blackbox_exporter modules
(blackbox/blackbox.yml), Grafana's settings, provisioning and dashboards
(grafana/), and the map the thermite exporter (lib/oh_metrics/exporter.py)
turns openHAB's REST answers into series with (exporter/map.json). render()
is pure: the same house and host give the same bytes, so `generate --check`
can compare.

What the house file decides is found from the conf/ it generates
(oh_render.build), never listed twice: the Things of each device, its
control ports (from its Things' URLs and port settings, and from its
integration modules' PORT and PROBE_PORTS) and the Items worth keeping
(select_point()). Device names and
addresses appear only in the output. Which of those readings say whether a
device answers is said once, in signals(): the availability checks are built
from it (health_paths()), and what it leaves unread is named (unobserved()),
never passed over.

Everything a unit needs that is not a file (listen addresses, retention,
mounts, arguments) is data here (services()), for the unit renderer in
lib/oh_deploy.py. Alert rules reuse exact active-path health semantics.
Prometheus sends its alerts nowhere: the gateway reads the firing ones from
it for the thermite app's Home (oh_identity.alerts).
"""

