@dataclasses.dataclass(frozen=True)
class Probe:
    """One TCP probe of a device's control port."""

    device: str
    room: str
    kind: str
    address: str
    port: int
    integrations: tuple[str, ...]

    @property
    def target(self) -> str:
        return f"{self.address}:{self.port}"


def _uses(device: dict, phase: str, name: str) -> bool:
    return name in ((device.get("controls") or {}).get(phase) or [])


def _integrations(device: dict) -> list[str]:
    """Every integration the device lists, observe first, without repeats."""
    controls = device.get("controls") or {}
    return list(dict.fromkeys([*(controls.get("observe") or []), *(controls.get("control") or [])]))


def thing_ports(thing: dict) -> list[int]:
    """The TCP ports a Thing's configuration talks to: its baseURL's and
    every `port` or `...Port` setting."""
    config = thing.get("config") or {}
    found: list[int] = []
    url = config.get("baseURL")
    if isinstance(url, str) and "://" in url:
        split = urllib.parse.urlsplit(url)
        default = {"http": 80, "https": 443}.get(split.scheme)
        port = split.port or default
        if port:
            found.append(port)
    for key, value in sorted(config.items()):
        if (key == "port" or key.endswith("Port")) and isinstance(value, int) and not isinstance(value, bool):
            found.append(value)
    return found


def _build(inventory: dict):
    # Imported here: oh_render needs PyYAML and the integrations, which the
    # exporter (this package, in the helper's image) must not.
    import oh_render

    return oh_render.build(inventory)


def probes(inventory: dict, conf=None) -> tuple[list[Probe], list[tuple[str, tuple[str, ...]]]]:
    """(TCP probes, (device, integrations) with an address but no port found)."""
    import oh_integrations

    conf = conf if conf is not None else _build(inventory)
    found: list[Probe] = []
    unknown: list[tuple[str, tuple[str, ...]]] = []
    for device in inventory.get("devices") or []:
        if not device.get("ip"):
            continue
        ident = device["id"]
        by_port: dict[int, list[str]] = {}
        for module in oh_integrations.REGISTRY:
            phases = [module.PHASE] + (["control"] if getattr(module, "CONTROL", False) else [])
            if not any(_uses(device, phase, module.NAME) for phase in phases) or module.NAME in UNPROBED:
                continue
            numbers: list[int] = []
            if isinstance(getattr(module, "PORT", None), int):
                numbers.append(module.PORT)
            file = conf.yaml.get(module.FILE)
            for uid, thing in sorted((file.things if file else {}).items()):
                if uid.split(":")[-1] == ident:
                    numbers += thing_ports(thing)
            numbers += CONTROL_PORTS.get(module.NAME, ())
            for number in numbers:
                names = by_port.setdefault(number, [])
                if module.NAME not in names:
                    names.append(module.NAME)
        if not by_port:
            unknown.append((ident, tuple(_integrations(device))))
            continue
        for number in sorted(by_port):
            found.append(Probe(ident, device["room"], device["kind"], device["ip"], number,
                               tuple(sorted(by_port[number]))))
    return found, unknown


def _options(item: dict) -> list[str] | None:
    """The values a String Item's state or command description offers."""
    import oh_conf
    metadata = item.get("metadata") or {}
    values: list[str] = []
    for key in ("stateDescription", "commandDescription"):
        text = ((metadata.get(key) or {}).get("config") or {}).get("options")
        if isinstance(text, str) and text:
            for value, _ in oh_conf.parse_options(text):
                if value and value not in values:
                    values.append(value)
    return values or None


def select_point(name: str, item: dict) -> tuple[str, str] | None:
    """(point, conversion) of an Item of a device worth keeping, else None.

    Kept: the device's reachability (`<id>_online`), its problem text
    (`<id>_problem`, as 0/1), and every Item tagged with the property Power,
    SoundVolume or Channel (power, power state, volume, mute, input), plus
    the Number Items a matrix or switch is commanded with (routing, EDID).
    Titles, artists, apps, keys and pairing Items are not: they are free text
    or carry no state worth a history.
    """
    kind = str(item.get("type") or "").split(":")[0]
    tags = set(item.get("tags") or [])
    if kind == "String" and name.endswith("_problem"):
        return "problem", "problem"
    if kind == "Switch" and name.endswith("_online"):
        return "reachable", "switch"
    if "Power" in tags:
        return {"Switch": ("power", "switch"), "String": ("power_state", "enum")}.get(kind)
    if "SoundVolume" in tags:
        return {"Switch": ("mute", "switch"), "Dimmer": ("volume", "number"),
                "Number": ("volume", "number")}.get(kind)
    if "Channel" in tags:
        return {"String": ("input", "enum"), "Number": ("input", "number")}.get(kind)
    if kind == "Number" and "Control" in tags:
        return ("edid", "number") if name.endswith("_edid") else ("routing", "number")
    return None


def exporter_map(inventory: dict, conf=None) -> dict:
    """The exporter's map: every device with its Things, and every Item kept
    (select_point()) with how its state becomes a number, plus each room's
    Source selector."""
    import oh_conf

    conf = conf if conf is not None else _build(inventory)
    house = oh_conf.House(inventory)
    things: dict[str, list[str]] = {}
    for file in conf.yaml.values():
        for uid in file.things:
            things.setdefault(uid.split(":")[-1], []).append(uid)
    devices: dict[str, dict] = {}
    items: dict[str, dict] = {}
    for device in house.devices:
        ident = device["id"]
        devices[ident] = {"room": device["room"], "kind": device["kind"], "label": house.label(device),
                          "things": sorted(things.get(ident, []))}
        for name, item in conf.points(ident):
            chosen = select_point(name, item)
            if chosen is None:
                continue
            point, convert = chosen
            entry = {"device": ident, "room": device["room"], "kind": device["kind"], "point": point,
                     "convert": convert}
            # Sony's rule explicitly publishes UNDEF for "nothing wrong";
            # other undefined telemetry remains unknown. Missing/NULL is not clear.
            if point == "problem" and _uses(device, "control", "sony_ip_control") and name == f"{ident}_problem":
                entry["clear_state"] = "UNDEF"
            if convert == "enum":
                entry["options"] = _options(item)
            items[name] = entry
    for file in conf.yaml.values():
        for name, item in file.items.items():
            groups = item.get("groups") or []
            if (name.startswith("loc_") and name.endswith("_source") and item.get("type") == "String"
                    and groups and str(groups[0]).startswith("loc_")):
                items[name] = {"device": "", "room": str(groups[0])[4:], "kind": "", "point": "source",
                               "convert": "enum", "options": _options(item)}
    rooms = {room: house.room_label(room) for room in house.rooms}
    paths, checks = health_paths(inventory, conf, items)
    result = {"version": MAP_VERSION, "rooms": rooms, "devices": devices, "items": dict(sorted(items.items())),
              "paths": paths, "health_checks": checks}
    from oh_features import threadpools
    if threadpools.enabled(house):
        result["handler_pool"] = dict(threadpools.ITEM_NAMES)
    return result


def health_paths(inventory: dict, conf, items: dict) -> tuple[dict, list[dict]]:
    """Required control checks from the same physical paths as Signal / Audio.

    Membership is per source, not room: local display sources bypass the
    receiver and matrices. Only control integrations supply availability
    checks; an optional Cast observer cannot invalidate working Sony control.
    Infrastructure serving routing is monitored even when every zone is Off.
    The exporter ignores these additive map fields; no new metrics or reads.
    """
    import oh_integrations
    from oh_conf import House
    from oh_features import remote_diagnostics, routing

    house = House(inventory)
    devices = {d["id"]: d for d in house.devices}
    physical = remote_diagnostics.manifest(house, conf)["rooms"]
    found, _ = probes(inventory, conf)
    checks: dict[tuple, dict] = {}

    def add(metric: str, labels: dict, bad: int, demand: dict | None) -> None:
        key = (metric, tuple(sorted(labels.items())), bad)
        check = checks.setdefault(key, {"metric": metric, "labels": labels, "bad": bad,
                                       "always": False, "required": []})
        if demand is None:
            check["always"] = True
        elif demand not in check["required"]:
            check["required"].append(demand)

    def device_checks(ident: str, demand: dict | None, node: dict | None = None) -> None:
        device = devices[ident]
        # HEOS supplies optional music transport, never an HDMI routing stage.
        # Its connection remains observable without invalidating a movie's
        # working Denon power/input path when that transport is unavailable.
        controls = set((device.get("controls") or {}).get("control") or []) - {"heos"}
        for module in oh_integrations.REGISTRY:
            if module.NAME not in controls:
                continue
            file = conf.yaml.get(module.FILE)
            for uid in (file.things if file else {}):
                if uid.split(":")[-1] == ident:
                    add("thermite_thing_online", {"thing": uid}, 0, demand)
        for probe in found:
            if probe.device == ident and set(controls).intersection(probe.integrations):
                add("probe_success", {"job": "device_tcp", "device": ident, "port": str(probe.port)}, 0, demand)
        if demand is None:
            return
        if any(s.get("device") == ident and s.get("point") == "problem" for s in items.values()):
            add("thermite_device_problem", {"device": ident}, 1, demand)
        power = []
        if node and node["role"] in ("receiver", "display") and (module := routing.stager(device)):
            zone = node.get("zone")
            stage = module.stage(device, None if zone == "main" else zone)
            power = [stage["power"]] if stage else []
        elif node and node["role"] == "source":
            power = [name for name, s in items.items() if s.get("device") == ident and s.get("point") == "power"]
        for name in power:
            if name in items:
                add("thermite_item_value", {"item": name, "point": "power"}, 0, demand)

    paths = {}
    for zone, entry in physical.items():
        name = routing.item_name(zone)
        paths[name] = {"label": entry["label"], "sources": {}}
        for source, path in entry["sources"].items():
            nodes = path["nodes"] + path.get("audioNodes", [])
            paths[name]["sources"][source] = list(dict.fromkeys(n["device"] for n in nodes))
            for node in nodes:
                device_checks(node["device"], {"item": name, "source": source}, node)
    for ident, device in devices.items():
        if device.get("kind") in ("hdmi_matrix", "usb_matrix", "hdmi_switch"):
            device_checks(ident, None)
    return paths, list(checks.values())


