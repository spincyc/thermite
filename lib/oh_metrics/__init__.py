def ports(host: dict) -> dict[str, int]:
    """Every port the metrics services use, with host.yaml `metrics:` overrides."""
    overrides = (host.get("metrics") or {}) if isinstance(host.get("metrics"), dict) else {}
    defaults = {
        "prometheus": PROMETHEUS_PORT,
        "node_exporter": NODE_EXPORTER_PORT,
        "blackbox": BLACKBOX_PORT,
        "grafana": GRAFANA_PORT,
        "exporter": EXPORTER_PORT,
        "alertmanager": 9093, "ntfy": 2586, "notifications": 9481,
    }
    return {name: int(overrides.get(f"{name}_port", port)) for name, port in defaults.items()}


def retention(host: dict) -> tuple[str, str]:
    """(time, size) Prometheus keeps, with host.yaml `metrics:` overrides."""
    overrides = host.get("metrics") if isinstance(host.get("metrics"), dict) else {}
    return str(overrides.get("retention", RETENTION_TIME)), str(overrides.get("retention_size", RETENTION_SIZE))


def systemd_units(host: dict) -> str:
    """node_exporter's --collector.systemd.unit-include pattern."""
    overrides = host.get("metrics") if isinstance(host.get("metrics"), dict) else {}
    names = (*SYSTEMD_UNITS, *(re.escape(str(unit)) for unit in overrides.get("units") or ()))
    return rf"({'|'.join(names)})\.(service|path)"


def openhab_address(host: dict) -> str:
    return f"{LOOPBACK}:{host['http_port']}"


